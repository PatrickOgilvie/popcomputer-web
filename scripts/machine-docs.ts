/**
 * The tables in docs/state-machines.md, generated from the machines' tables in
 * src/, so the docs cannot drift from the code.
 *
 * Run: bun scripts/machine-docs.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { transactionTable } from '../src/effect/database.js'
import { pendingCacheTagsTable, pendingPurgesTable } from '../src/effect/response-cache.js'
import { flashCookieTable } from '../src/flash.js'
import { rows, type TableRow } from '../src/machine.js'

const repoRoot = join(import.meta.dir, '..')

export const DOC_PATH = join(repoRoot, 'docs', 'state-machines.md')

const START = '<!-- machine tables: generated by scripts/machine-docs.ts -->'
const END = '<!-- machine tables end -->'

/** Every machine whose table is the code. */
const machines: ReadonlyArray<{ readonly name: string; readonly source: string; readonly rows: ReadonlyArray<TableRow> }> = [
  { name: 'The flash cookie', source: 'src/flash.ts', rows: rows(flashCookieTable) },
  { name: 'A transaction', source: 'src/effect/database.ts', rows: rows(transactionTable) },
  { name: 'Purges a piece of work owes', source: 'src/effect/response-cache.ts', rows: rows(pendingPurgesTable) },
  { name: 'Tags a stored response carries', source: 'src/effect/response-cache.ts', rows: rows(pendingCacheTagsTable) },
]

const escapeCell = (text: string): string => text.replaceAll('|', '\\|')

function renderMachine(machine: (typeof machines)[number]): string {
  const lines = machine.rows.map((row) => `| ${row.from} | \`${row.on}\` | ${row.to} | ${escapeCell(row.mark)} |`)

  return [`### ${machine.name}`, '', `\`${machine.source}\``, '', '| State | Event | Moves to | Mark |', '|---|---|---|---|', ...lines].join('\n')
}

/** docs/state-machines.md with its generated section as the code says. */
export function renderDoc(doc: string): string {
  const from = doc.indexOf(START)
  const to = doc.indexOf(END)

  if (from === -1 || to === -1) throw new Error(`${DOC_PATH} has lost its generated section's markers.`)

  return `${doc.slice(0, from)}${START}\n\n${machines.map(renderMachine).join('\n\n')}\n\n${doc.slice(to)}`
}

if (import.meta.main) {
  writeFileSync(DOC_PATH, renderDoc(readFileSync(DOC_PATH, 'utf8')))
  console.log(`Wrote ${DOC_PATH}`)
}
